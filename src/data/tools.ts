export function localizeTool(tool: Tool, lang: Lang): Tool {
  if (lang === 'en') return tool;
  const tr = tool.translations?.[lang];
  if (!tr) return tool;
  return { ...tool, ...tr };
}

export function useLocalizedTools(tools: Tool[], lang: Lang): Tool[] {
  return tools.map((t) => localizeTool(t, lang));
}
